#!/usr/bin/env node
'use strict';
/**
 * 把「手册」导出成纯静态站点（用于 GitHub Pages / 任意静态托管）
 *
 *   node server/export-static.js              # 输出到 dist/
 *   node server/export-static.js --out site   # 自定义输出目录
 *   node server/export-static.js --db other.json
 *
 * 产物结构（全部用相对路径，可放在子路径下，如 /freshman-handbook/）：
 *   dist/
 *     index.html  style.css  app.js  .nojekyll
 *     api/schools.json
 *     api/school/<slug>.json
 *     api/entry/<slug>/<id>.json
 *     uploads/<图片>
 *
 * 说明：
 *  - 静态站没有服务端，因此「密码解锁」功能不可用；脚本发现仍有开启密码锁的
 *    条目会直接报错退出，避免把付费内容误发到公网或导出成半截页面。
 *  - 所有以 / 开头的资源路径会被改写成相对路径，适配 GitHub Pages 的子路径部署。
 */
const fs = require('node:fs');
const path = require('node:path');
const { publicSchool } = require('./lib/public');

const ROOT = path.resolve(__dirname, '..');
const MARKER = '.handbook-static';

function arg(name, fallback) {
  const i = process.argv.indexOf('--' + name);
  if (i > -1 && process.argv[i + 1]) return process.argv[i + 1];
  return fallback;
}

const OUT = path.resolve(ROOT, arg('out', 'dist'));
const DB_FILE = path.resolve(ROOT, arg('db', path.join('server', 'data', 'db.json')));

/* 把 "/uploads/x.jpg" 改写成 "uploads/x.jpg"，外链（https://、//）原样保留 */
function relativize(value) {
  if (typeof value === 'string') {
    if (value.startsWith('/') && !value.startsWith('//')) return value.slice(1);
    return value;
  }
  if (Array.isArray(value)) return value.map(relativize);
  if (value && typeof value === 'object') {
    const out = {};
    for (const k of Object.keys(value)) out[k] = relativize(value[k]);
    return out;
  }
  return value;
}

function writeJson(relPath, data) {
  const full = path.join(OUT, relPath);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, JSON.stringify(data, null, 2) + '\n', 'utf8');
  return relPath;
}

function main() {
  if (!fs.existsSync(DB_FILE)) {
    console.error('  读不到数据文件：' + DB_FILE);
    process.exit(1);
  }
  const db = JSON.parse(fs.readFileSync(DB_FILE, 'utf8'));
  const slugs = Object.keys(db.schools || {});
  if (!slugs.length) {
    console.error('  数据文件里没有任何学校。');
    process.exit(1);
  }

  /* 安全闸门：仍有开启密码锁的条目就停手 */
  const locked = [];
  for (const slug of slugs) {
    for (const sec of db.schools[slug].sections || []) {
      for (const e of sec.entries || []) {
        if (e.lock && e.lock.enabled) locked.push(slug + ' / ' + sec.title + ' / ' + e.title);
      }
    }
  }
  if (locked.length) {
    console.error('');
    console.error('  导出中止：以下条目仍开启着密码锁，静态站无法校验密码。');
    for (const s of locked) console.error('    - ' + s);
    console.error('  处理方式：在后台把这些条目改为「公开」，或直接在 db.json 里把 lock.enabled 设为 false。');
    console.error('');
    process.exit(1);
  }

  /* 清理旧产物：只删自己生成过的目录，避免误删 */
  if (fs.existsSync(OUT)) {
    const entries = fs.readdirSync(OUT);
    if (entries.length && !fs.existsSync(path.join(OUT, MARKER))) {
      console.error('  目标目录非空且不是导出产物：' + OUT);
      console.error('  请换一个 --out 目录，或手工清空后重试。');
      process.exit(1);
    }
    fs.rmSync(OUT, { recursive: true, force: true });
  }
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, MARKER), 'generated by server/export-static.js\n', 'utf8');
  /* .nojekyll：阻止 Pages 用 Jekyll 处理，避免下划线开头的文件被忽略 */
  fs.writeFileSync(path.join(OUT, '.nojekyll'), '', 'utf8');

  /* 1. 前端静态文件 */
  const webDir = path.join(ROOT, 'web');
  for (const f of fs.readdirSync(webDir)) {
    const src = path.join(webDir, f);
    if (!fs.statSync(src).isFile()) continue;
    let buf = fs.readFileSync(src);
    if (f === 'index.html') {
      /* 注入静态模式标记：前端据此改读 .json 而不是 /api */
      let html = buf.toString('utf8');
      html = html.replace(
        '<script src="app.js"></script>',
        '<script>window.HANDBOOK_STATIC=1;</script>\n<script src="app.js"></script>'
      );
      buf = Buffer.from(html, 'utf8');
    }
    fs.writeFileSync(path.join(OUT, f), buf);
  }

  /* 2. 图片资源 */
  const upDir = path.join(ROOT, 'uploads');
  if (fs.existsSync(upDir)) {
    fs.mkdirSync(path.join(OUT, 'uploads'), { recursive: true });
    for (const f of fs.readdirSync(upDir)) {
      const src = path.join(upDir, f);
      if (fs.statSync(src).isFile()) fs.copyFileSync(src, path.join(OUT, 'uploads', f));
    }
  }

  /* 3. 接口快照 */
  const written = [];
  writeJson('api/schools.json', slugs.map((slug) => ({ slug, name: db.schools[slug].name })));
  for (const slug of slugs) {
    const school = db.schools[slug];
    writeJson(path.join('api', 'school', slug + '.json'), relativize(publicSchool(school)));
    let n = 0;
    for (const sec of school.sections || []) {
      for (const e of sec.entries || []) {
        writeJson(path.join('api', 'entry', slug, e.id + '.json'), relativize({
          title: e.title,
          blocks: e.blocks || [],
          locked: false,
        }));
        n++;
      }
    }
    written.push({ slug, name: school.name, entries: n });
  }

  const total = written.reduce((a, b) => a + b.entries, 0);
  console.log('');
  console.log('  导出完成：' + OUT);
  for (const w of written) console.log('    ' + w.name + '（' + w.slug + '）：' + w.entries + ' 个条目');
  console.log('  合计 ' + total + ' 个条目、' + written.length + ' 所学校');
  console.log('');
  console.log('  本地预览：npx serve "' + OUT + '"   或   任意静态服务器打开 index.html');
  console.log('  部署 Pages：推到 main 后由 .github/workflows/pages.yml 自动发布');
  console.log('');
}

main();
